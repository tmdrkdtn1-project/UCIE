"""W02: inert, source-anchored Virtual Library entry contract.

This is a *candidate* data model, not the finished indexed Library and not
a project import/export API. Incoming public metadata is untrusted. Results
contain no source code, raw snippets, runnable instructions or private data.
"""
from __future__ import annotations

import hashlib
import re

from .public_discovery import SOURCE_SKILL
from .skill_profiles import PROFILE
from .source_registry import SourceRegistryError, get_source

SCHEMA = "UCIE_W02_PUBLIC_LIBRARY_ENTRY_V1"
KINDS = frozenset({
    "PREVENTION_RULE", "DEVELOPMENT_ENGINE", "REUSABLE_SKILL",
    "LEARNING_LOGIC", "TEST_RECIPE", "UCIE_EXPERIENCE",
})
EXTERNAL_CANDIDATE_KINDS = KINDS - {"UCIE_EXPERIENCE"}
HEX64 = re.compile(r"[a-f0-9]{64}\Z")
TOKEN = re.compile(r"[A-Z][A-Z0-9_]{2,63}\Z")
DEPENDENCY = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,47}\Z")
VERSION = re.compile(r"[A-Za-z0-9][A-Za-z0-9._+-]{0,31}\Z")
PR_REFERENCE = re.compile(
    r"(?:pr|fix-pr):([1-9][0-9]*):([a-f0-9]{40})(?::([a-f0-9]{64}))?\Z")
COMMIT_REFERENCE = re.compile(r"commit:([a-f0-9]{40})\Z")

# All fields in this shape are generated by UCIE and never lifted verbatim
# from arbitrary source text. "license_status" is explicitly *not* a signoff.
ALLOWED_INPUT_FIELDS = frozenset({
    "kind", "source_id", "evidence_reference", "evidence_sha256",
    "purpose_code", "version_scope", "dependencies",
})


class LibraryEntryError(ValueError):
    pass


def _safe_reference(source: dict, reference: str) -> tuple[str, str]:
    if type(reference) is not str or not 1 <= len(reference) <= 196:
        raise LibraryEntryError("invalid public evidence reference")
    source_id = source["source_id"]
    if source_id.startswith("doc:"):
        if reference != source["public_url"]:
            raise LibraryEntryError("document reference is not a pinned official URL")
        return reference, "PUBLIC_DOCUMENT_REVISION_NOT_PINNED"
    repo = source_id.removeprefix("repo:")
    pr = PR_REFERENCE.fullmatch(reference)
    if pr is not None:
        number, sha = int(pr.group(1)), pr.group(2)
        if number > 1_000_000_000:
            raise LibraryEntryError("unreasonably large public PR number")
        return "https://github.com/" + repo + "/pull/" + str(number), sha
    commit = COMMIT_REFERENCE.fullmatch(reference)
    if commit is not None and repo == "git/git":
        sha = commit.group(1)
        return "https://github.com/git/git/commit/" + sha, sha
    raise LibraryEntryError("unsupported or unbound public revision")


def build_library_entry(record: dict) -> dict:
    """Normalize one approved-source public candidate to a safe library item."""
    if (type(record) is not dict or set(record) != ALLOWED_INPUT_FIELDS):
        raise LibraryEntryError("invalid library candidate fields")
    kind = record["kind"]
    if kind not in EXTERNAL_CANDIDATE_KINDS or type(kind) is not str:
        raise LibraryEntryError("external-source entries cannot assert UCIE experience")
    try:
        source = get_source(record["source_id"])
    except SourceRegistryError as exc:
        raise LibraryEntryError("source is not an approved public source") from exc
    purpose = record["purpose_code"]
    if type(purpose) is not str or TOKEN.fullmatch(purpose) is None:
        raise LibraryEntryError("unsafe or unclassified capability purpose")
    digest = record["evidence_sha256"]
    if type(digest) is not str or HEX64.fullmatch(digest) is None:
        raise LibraryEntryError("invalid public evidence fingerprint")
    version = record["version_scope"]
    if type(version) is not str or VERSION.fullmatch(version) is None:
        raise LibraryEntryError("invalid bounded version scope")
    deps = record["dependencies"]
    if (type(deps) is not list or len(deps) > 8
            or any(type(x) is not str or DEPENDENCY.fullmatch(x) is None
                   for x in deps)
            or len(set(deps)) != len(deps)):
        raise LibraryEntryError("invalid or duplicate capability dependencies")
    evidence_ref = record["evidence_reference"]
    url, revision = _safe_reference(source, evidence_ref)
    repo = source["source_id"].split(":", 1)[1]
    skill = SOURCE_SKILL.get(repo)
    if skill not in PROFILE:
        raise LibraryEntryError("public domain skill profile absent")
    # Dependably separate evidence digest from signed/verified statements.
    fingerprint = hashlib.sha256(
        ("\x1f".join((kind, source["source_id"], evidence_ref, digest, purpose)))
        .encode("ascii")).hexdigest()
    return {
        "schema": SCHEMA,
        "library_item_id": fingerprint,
        "kind": kind,
        "source_id": source["source_id"],
        "source_kind": source["source_kind"],
        "public_url": url,
        "evidence_reference": evidence_ref,
        "evidence_sha256": digest,
        "revision_hint": revision,
        "purpose_code": purpose,
        "skill_profile": skill,
        "domain": PROFILE[skill]["domain"],
        "version_scope_claim": version,
        "version_applicability_verified": False,
        "dependencies": list(deps),
        "entry_status": "UNVERIFIED_CANDIDATE_ONLY",
        "approval_status": "NOT_APPROVED",
        "source_license_status": source["license_verdict"],
        "independent_qa_status": "NOT_PERFORMED",
        "human_approved": False,
        "owner_signed": False,
        "auto_promoted": False,
        "export_allowed": False,
        "source_executed": False,
        "source_text_retained": False,
    }


def preview_library_contract() -> dict:
    """Expose an actual importable in-memory schema, with no DB/GET/writes."""
    return {
        "schema": SCHEMA,
        "status": "LIBRARY_CANDIDATE_CONTRACT_IMPLEMENTED_NOT_INDEXED",
        "kinds": sorted(KINDS),
        "external_candidate_kinds": sorted(EXTERNAL_CANDIDATE_KINDS),
        "required_input_fields": sorted(ALLOWED_INPUT_FIELDS),
        "search_index_implemented": False,
        "operating_database_writes": 0,
        "network_requests": 0,
        "project_code_access": False,
        "unsigned_candidate_auto_export": False,
    }

class OfflineProductLifecycleError(ValueError):
    """No implicit product approval or unsafe fallback on a failed check."""


def _canon(data: dict) -> bytes:
    if type(data) is not dict:
        raise OfflineProductLifecycleError("structured review object required")
    return (json.dumps(data, sort_keys=True, ensure_ascii=True,
                       separators=(",", ":"), allow_nan=False)+"\n").encode("ascii")


def _parse(raw: bytes, maximum: int) -> dict:
    if type(raw) is not bytes or not 0 < len(raw) <= maximum:
        raise OfflineProductLifecycleError("unsafe bounded local metadata bytes")
    def unique(pairs):
        if len({key for key, _ in pairs}) != len(pairs):
            raise OfflineProductLifecycleError("duplicate untrusted fields")
        return dict(pairs)
    try:
        data = json.loads(raw.decode("ascii"), object_pairs_hook=unique,
                          parse_constant=lambda _: (_ for _ in ()).throw(
                              OfflineProductLifecycleError("nonfinite value")))
    except (UnicodeError, TypeError, ValueError) as exc:
        raise OfflineProductLifecycleError("untrusted metadata structure") from exc
    if type(data) is not dict or _canon(data) != raw:
        raise OfflineProductLifecycleError("noncanonical local metadata")
    return data


def _read(file: Path, maximum: int) -> bytes:
    if (file.is_symlink() or not file.is_file()
            or not 0 < file.stat().st_size <= maximum):
        raise OfflineProductLifecycleError("unsafe missing or oversized local file")
    raw = file.read_bytes()
    if len(raw) != file.stat().st_size:
        raise OfflineProductLifecycleError("changed file during read")
    return raw


def _parent_safe(path: Path) -> None:
    if not isinstance(path, Path) or not path.is_absolute():
        raise OfflineProductLifecycleError("absolute Windows recipient path required")
    if path.is_symlink() or path.parent.is_symlink():
        raise OfflineProductLifecycleError("symlinked recipient or parent forbidden")


def _bundle_root(root: Path) -> Path:
    _parent_safe(root)
    if root.name != RELEASE_NAME or not root.is_dir():
        raise OfflineProductLifecycleError("explicit UCIE private release candidate required")
    wheel_dir = root/"wheels"
    if wheel_dir.is_symlink() or not wheel_dir.is_dir():
        raise OfflineProductLifecycleError("unsafe wheelhouse directory")
    return root


def _vendor_wheels(folder: Path) -> dict[str, Path]:
    if folder.is_symlink() or not folder.is_dir():
        raise OfflineProductLifecycleError("untrusted vendor wheelhouse")
    seen: dict[str, Path] = {}
    files = list(folder.iterdir())
    if len(files) != len(vendor.PINNED):
        raise OfflineProductLifecycleError("not exactly three approved vendors")
    for f in files:
        if f.is_symlink() or not f.is_file() or f.suffix != ".whl":
            raise OfflineProductLifecycleError("unreviewed vendor wheel member")
        inspected = wheel_gate._inspect_wheel(f)   # REAL RECORD/ZIP/bounds
        identity = (inspected.get("name"), inspected.get("version"))
        if identity not in vendor.PINNED or identity[0] in seen:
            raise OfflineProductLifecycleError("unapproved wheel dependency")
        seen[identity[0]] = f
    if set(seen) != {name for name, _ in vendor.PINNED}:
        raise OfflineProductLifecycleError("incomplete official vendor closure")
    return seen


def _inventory(wheels: Path) -> tuple[list[dict], Path, dict[str, str]]:
    if wheels.is_symlink() or not wheels.is_dir():
        raise OfflineProductLifecycleError("untrusted wheelhouse location")
    files = list(wheels.iterdir())
    if len(files) != 4:
        raise OfflineProductLifecycleError("wheelhouse must have exactly 4 wheels")
    product_files = [wheels/name for name in PRODUCT_NAMES.values()
                     if (wheels/name).exists() or (wheels/name).is_symlink()]
    if len(product_files) != 1:
        raise OfflineProductLifecycleError("exactly one approved first-party product version required")
    main = product_files[0]
    if main.is_symlink() or not main.is_file():
        raise OfflineProductLifecycleError("pinned first-party product wheel absent")
    item = wheel_gate._inspect_wheel(main)
    if (item.get("name") != full.FIRST_PARTY_NAME or
            item.get("version") not in PRODUCT_NAMES or
            main.name != PRODUCT_NAMES[item.get("version")] or
            item.get("metadata_record_sha256_verified") is not True):
        raise OfflineProductLifecycleError("first-party exact identity/RECORD invalid")
    vend = _vendor_wheels_subset(wheels, main.name)
    hashes = {name: sha256(path.read_bytes()).hexdigest()
              for name, path in vend.items()}
    rows = [{
        "distribution": full.FIRST_PARTY_NAME, "version": item["version"],
        "filename": main.name, "bytes": main.stat().st_size,
        "sha256": sha256(main.read_bytes()).hexdigest(),
        "license_review_approved": False,
    }]
    for name, version in vendor.PINNED:
        file = vend[name]
        rows.append({
            "distribution": name, "version": version, "filename": file.name,
            "bytes": file.stat().st_size,
            "sha256": hashes[name], "license_review_approved": False,
        })
    return rows, main, hashes


def _vendor_wheels_subset(wheels: Path, product_name: str) -> dict[str, Path]:
    members = [p for p in wheels.iterdir() if p.name != product_name]
    if len(members) != 3:
        raise OfflineProductLifecycleError("wrong vendor count")
    seen = {}
    for f in members:
        if not f.is_file() or f.is_symlink() or f.suffix != ".whl":
            raise OfflineProductLifecycleError("non-wheel in verified wheelhouse")
        entry = wheel_gate._inspect_wheel(f)
        name, version = entry.get("name"), entry.get("version")
        if (name, version) not in vendor.PINNED or name in seen:
            raise OfflineProductLifecycleError("unexpected vendor version or duplicate")
        seen[name] = f
    if set(seen) != {name for name, _ in vendor.PINNED}:
        raise OfflineProductLifecycleError("missing pinned vendor")
    return seen


def _sbom(entries: list[dict], product_hash: str) -> dict:
    """Machine-readable source-independent inventory; license is NOASSERTION."""
    packages = []
    for i, row in enumerate(entries):
        packages.append({
            "SPDXID": "SPDXRef-UCIE-" + str(i),
            "name": row["distribution"],
            "versionInfo": row["version"],
            "downloadLocation": "NOASSERTION",
            "filesAnalyzed": False,
            "licenseConcluded": "NOASSERTION",
            "licenseDeclared": "NOASSERTION",
            "copyrightText": "NOASSERTION",
            "checksums": [{"algorithm": "SHA256", "checksumValue": row["sha256"]}],
            "externalRefs": [],
        })
    return {
        "spdxVersion": SBOM_SCHEMA, "dataLicense": "CC0-1.0",
        "SPDXID": "SPDXRef-DOCUMENT",
        "name": "UCIE_PRIVATE_RC_NOT_LEGAL_CLEARANCE",
        "documentNamespace":
            "https://example.invalid/ucie-private-technical-rc/" + product_hash,
        "creationInfo": {"creators": ["Tool: UCIE-B3B4-technical-QA-v01"]},
        "packages": packages,
    }


def build_private_qa_bundle(root: Path, product: Path, vendors: Path,
                            record_bytes: bytes, signature_bytes: bytes) -> dict:
    """Exclusive-create FOUR local wheels + SPDX + manifest, no network, NO_GO.

    This outputs technical QA bytes ONLY. Real vendor redistribution is not
    authorized merely because a bundle directory exists; GitHub CI deletes it.
    """
    _parent_safe(root)
    if root.name != RELEASE_NAME or root.exists() or root.is_symlink():
        raise OfflineProductLifecycleError("fresh bounded UCIE bundle required")
    if (product.is_symlink() or not product.is_file()
            or product.name not in PRODUCT_NAMES.values()):
        raise OfflineProductLifecycleError("exact previously validated UCIE wheel required")
    verified = wheel_gate._inspect_wheel(product)
    if (verified.get("name") != full.FIRST_PARTY_NAME
            or verified.get("version") not in PRODUCT_NAMES
            or product.name != PRODUCT_NAMES[verified.get("version")]
            or verified.get("metadata_record_sha256_verified") is not True):
        raise OfflineProductLifecycleError("first party wheel corrupt")
    sources = _vendor_wheels(vendors)
    record = entitlement._decode(record_bytes, maximum=MAX_ENTITLEMENT)
    signature = entitlement._decode(signature_bytes, maximum=MAX_SIGNATURE)
    if (record.get("product_wheel_sha256") != sha256(product.read_bytes()).hexdigest()
            or record.get("vendor_wheels_sha256") !=
                {name: sha256(path.read_bytes()).hexdigest() for name,path in sources.items()}
            or record.get("scope") != entitlement.SCOPE
            or signature.get("scope") != entitlement.SCOPE
            or record.get("four_pillars") != list(PILLARS)):
        raise OfflineProductLifecycleError("unbound candidate unsigned/invalid content")
    root.mkdir()
    wheel_out = root/"wheels"
    wheel_out.mkdir()
    for file in [product, *(sources[name] for name,_ in vendor.PINNED)]:
        target = wheel_out/file.name
        with target.open("xb") as f:
            f.write(file.read_bytes())
    rows, product_file, digests = _inventory(wheel_out)
    spdx = _canon(_sbom(rows, sha256(product_file.read_bytes()).hexdigest()))
    (root/"sbom.spdx.json").write_bytes(spdx)
    (root/"NOTICE_REVIEW_REQUIRED.txt").write_bytes(NOTICE.encode("ascii"))
    (root/"entitlement.json").write_bytes(record_bytes)
    (root/"entitlement.sig.json").write_bytes(signature_bytes)
    manifest = {
        "schema": BUNDLE_SCHEMA,
        "status": "TECHNICAL_CANDIDATE_NOT_APPROVED_FOR_CUSTOMER_DISTRIBUTION",
        "wheel_files": rows,
        "spdx_sha256": sha256(spdx).hexdigest(),
        "notice_sha256": sha256(NOTICE.encode("ascii")).hexdigest(),
        "entitlement_sha256": sha256(record_bytes).hexdigest(),
        "signature_sha256": sha256(signature_bytes).hexdigest(),
        "vendor_license_legal_review_approved": False,
        "customer_distribution_authorized": False,
        "four_pillars": list(PILLARS),
    }
    (root/"manifest.json").write_bytes(_canon(manifest))
    return {
        "schema": SCHEMA,
        "status": NO_GO,
        "exact_wheel_count": len(rows),
        "product_sha256": rows[0]["sha256"],
        "pinned_vendor_sha256": digests,
        "spdx_packages": len(rows),
        "customer_distribution_authorized": False,
    }


def verify_private_qa_bundle(
    root: Path, *, public_pem: bytes, expected_owner_key_id: str,
    expected_recipient_token_sha256: str, expected_rights_packet_sha256: str,
    min_serial: int, now: datetime | None = None,
) -> dict:
    """Verify every wheel, license binding and fixed SBOM before installation/launch."""
    _bundle_root(root)
    if {f.name for f in root.iterdir()} != {
        "wheels", "sbom.spdx.json", "NOTICE_REVIEW_REQUIRED.txt",
        "entitlement.json", "entitlement.sig.json", "manifest.json"
    }:
        raise OfflineProductLifecycleError("unexpected package root file")
    manifest = _parse(_read(root/"manifest.json", MAX_MANIFEST), MAX_MANIFEST)
    entries, product, vendor_hashes = _inventory(root/"wheels")
    if (manifest.get("schema") != BUNDLE_SCHEMA
            or manifest.get("status") !=
                "TECHNICAL_CANDIDATE_NOT_APPROVED_FOR_CUSTOMER_DISTRIBUTION"
            or manifest.get("wheel_files") != entries
            or manifest.get("vendor_license_legal_review_approved") is not False
            or manifest.get("customer_distribution_authorized") is not False
            or manifest.get("four_pillars") != list(PILLARS)):
        raise OfflineProductLifecycleError("bundle manifest authoritative claim invalid")
    notice = _read(root/"NOTICE_REVIEW_REQUIRED.txt", 3000)
    if notice != NOTICE.encode("ascii") or sha256(notice).hexdigest() != manifest.get("notice_sha256"):
        raise OfflineProductLifecycleError("legal rights hold or notice changed")
    sbom_bytes = _read(root/"sbom.spdx.json", MAX_SBOM)
    expected_sbom = _canon(_sbom(entries, entries[0]["sha256"]))
    if (sbom_bytes != expected_sbom
            or sha256(sbom_bytes).hexdigest() != manifest.get("spdx_sha256")):
        raise OfflineProductLifecycleError("SBOM inventory changed from exact wheel bytes")
    signed = _read(root/"entitlement.json", MAX_ENTITLEMENT)
    signature = _read(root/"entitlement.sig.json", MAX_SIGNATURE)
    if (sha256(signed).hexdigest() != manifest.get("entitlement_sha256")
            or sha256(signature).hexdigest() != manifest.get("signature_sha256")):
        raise OfflineProductLifecycleError("signed entitlement sidecar drift")
    crypt = entitlement.verify_private_entitlement(
        signed, signature, public_pem,
        expected_owner_key_id=expected_owner_key_id,
        min_serial=min_serial,
        expected_recipient_token_sha256=expected_recipient_token_sha256,
        expected_product_wheel_sha256=entries[0]["sha256"],
        expected_product_version=entries[0]["version"],
        expected_vendor_wheels_sha256=vendor_hashes,
        expected_rights_packet_sha256=expected_rights_packet_sha256,
        now=datetime.now(timezone.utc) if now is None else now,
    )
    if (crypt.get("private_product_ed25519_signature_verified") is not True
            or crypt.get("customer_distribution_authorized") is not False):
        raise OfflineProductLifecycleError("signature did not remain non-commercial")
    return {
        "schema": SCHEMA, "status": NO_GO,
        "product_sha256": entries[0]["sha256"],
        "product_version": entries[0]["version"],
        "pinned_vendor_sha256": vendor_hashes,
        "exact_wheel_count": 4,
        "real_ed25519_verified": True,
        "owner_signed_serial": crypt["release_serial"],
        "four_pillars_bound": list(PILLARS),
        "licensed_recipient_binding_technically_verified": True,
        "independent_legal_customer_and_source_acceptance": False,
        "customer_distribution_authorized": False,
    }


def _recipient(root: Path) -> Path:
    _parent_safe(root)
    if (root.name != RECIPIENT_NAME
            or (os.name == "nt" and root.resolve() == Path("D:/UCIE").resolve())
            or (root/".git").exists() or (root/"runtime").exists()):
        raise OfflineProductLifecycleError("not an isolated designated recipient")
    if root.exists():
        if not root.is_dir() or (root/"slots").is_symlink():
            raise OfflineProductLifecycleError("unsafe recipient directory")
        if set(p.name for p in root.iterdir()) - {"slots", "active.json", LAUNCHER_NAME}:
            raise OfflineProductLifecycleError("recipient has unrecognized data")
        script=root/LAUNCHER_NAME
        if script.exists() or script.is_symlink():
            if _read(script,6000)!=LAUNCHER.encode("utf-8"):
                raise OfflineProductLifecycleError("untrusted launcher")
    return root


def _slot_id(bundle: Path) -> str:
    raw = _read(bundle/"manifest.json", MAX_MANIFEST) + _read(
        bundle/"entitlement.sig.json", MAX_SIGNATURE)
    return sha256(raw).hexdigest()[:16]


def _active(root: Path) -> dict | None:
    ptr=root/"active.json"
    if ptr.exists() or ptr.is_symlink():
        obj=_parse(_read(ptr,2000),2000)
        if (set(obj) != {"schema","active_slot","previous_slot","customer_distribution_authorized"}
                or obj["schema"] != SCHEMA
                or obj["customer_distribution_authorized"] is not False
                or type(obj["active_slot"]) is not str or SLOT_NAME.fullmatch(obj["active_slot"]) is None
                or obj["previous_slot"] is not None and (
                    type(obj["previous_slot"]) is not str or SLOT_NAME.fullmatch(obj["previous_slot"]) is None)):
            raise OfflineProductLifecycleError("untrusted active slot state")
        return obj
    return None


def _pointer(root: Path, selected: str, previous: str | None) -> None:
    if SLOT_NAME.fullmatch(selected) is None or (
            previous is not None and SLOT_NAME.fullmatch(previous) is None):
        raise OfflineProductLifecycleError("invalid active slot pointer")
    pending=root/"active.pending.json"
    if pending.exists() or pending.is_symlink():
        raise OfflineProductLifecycleError("previous pending switch needs manual review")
    data=_canon({
        "schema":SCHEMA,"active_slot":selected,"previous_slot":previous,
        "customer_distribution_authorized":False,
    })
    with pending.open("xb") as out:
        out.write(data)
        out.flush()
        os.fsync(out.fileno())
    os.replace(pending,root/"active.json")


def _env() -> dict[str,str]:
    keep=("PATH","SystemRoot","SYSTEMROOT","WINDIR","TEMP","TMP",
          "HOME","USERPROFILE","HOMEDRIVE","HOMEPATH","COMSPEC")
    e={key:os.environ[key] for key in keep if key in os.environ}
    e.update(PIP_NO_INDEX="1",PIP_DISABLE_PIP_VERSION_CHECK="1",
             PYTHONDONTWRITEBYTECODE="1")
    return e



def verify_selected(recipient:Path,*,public_pem:bytes,
                    expected_owner_key_id:str,expected_recipient_token_sha256:str,
                    expected_rights_packet_sha256:str,min_serial:int,
                    now:datetime|None=None) -> dict:
    root=_recipient(recipient)
    active=_active(root)
    if not active:
        raise OfflineProductLifecycleError("no authenticated installed slot")
    slot=active["active_slot"]
    path=root/"slots"/slot
    if path.is_symlink() or not path.is_dir():
        raise OfflineProductLifecycleError("active installed slot absent")
    check=verify_private_qa_bundle(
        path/RELEASE_NAME,public_pem=public_pem,
        expected_owner_key_id=expected_owner_key_id,
        expected_recipient_token_sha256=expected_recipient_token_sha256,
        expected_rights_packet_sha256=expected_rights_packet_sha256,
        min_serial=min_serial,now=now)
    receipt=_parse(_read(path/"receipt.json",2500),2500)
    if (receipt.get("schema")!=SCHEMA or receipt.get("slot")!=slot
            or receipt.get("product_wheel_sha256")!=check["product_sha256"]
            or receipt.get("signed_serial")!=check["owner_signed_serial"]
            or receipt.get("customer_distribution_authorized") is not False):
        raise OfflineProductLifecycleError("untrusted installed receipt/pointer")
    child=path/"venv"/"Scripts"/"python.exe"
    if child.is_symlink() or not child.is_file():
        raise OfflineProductLifecycleError("installed first-party executable removed")
    return {
        **check,"active_slot":slot,
        "installed_customer_venv_present":True,
        "runtime_owner_license_reverified":True,
        "customer_distribution_authorized":False,
    }


def rollback(
    recipient:Path,*,public_pem:bytes,expected_owner_key_id:str,
    expected_recipient_token_sha256:str,expected_rights_packet_sha256:str,
    min_serial:int,consent:str,now:datetime|None=None,
) -> dict:
    if consent!=ROLLBACK_CONSENT:
        raise OfflineProductLifecycleError("explicit signed previous slot consent required")
    root=_recipient(recipient)
    active=_active(root)
    if not active or not active.get("previous_slot"):
        raise OfflineProductLifecycleError("no previous authenticated slot")
    old=active["previous_slot"]
    old_path=root/"slots"/old
    if old_path.is_symlink() or not old_path.is_dir():
        raise OfflineProductLifecycleError("previous slot was removed")
    # Verify previous signed entitlement with CURRENT owner serial floor.
    check=verify_private_qa_bundle(
        old_path/RELEASE_NAME,public_pem=public_pem,
        expected_owner_key_id=expected_owner_key_id,
        expected_recipient_token_sha256=expected_recipient_token_sha256,
        expected_rights_packet_sha256=expected_rights_packet_sha256,
        min_serial=min_serial,now=now)
    r=_parse(_read(old_path/"receipt.json",2500),2500)
    if (r.get("slot")!=old or r.get("product_wheel_sha256")!=check["product_sha256"]
            or not (old_path/"venv"/"Scripts"/"python.exe").is_file()):
        raise OfflineProductLifecycleError("previous slot does not pass signed rollback")
    _pointer(root,old,active["active_slot"])
    return {
        "schema":SCHEMA,"status":"PRIVATE_SIGNED_PREVIOUS_SLOT_SELECTED_NO_GO",
        "active_slot":old, "previous_slot":active["active_slot"],
        "customer_distribution_authorized":False,
    }


def remove_technical_install(recipient:Path,*,consent:str) -> dict:
    """Technical uninstall: only registered slots, reject unexpected user data.

    This never touches a project checkout, shared host Python, schedulers,
    owner data or any path outside the single explicit recipient directory.
    """
    if consent!=REMOVE_CONSENT or os.name!="nt":
        raise OfflineProductLifecycleError("explicit recipient-local uninstall required")
    root=_recipient(recipient)
    if not root.is_dir() or not _active(root):
        raise OfflineProductLifecycleError("no registered product to uninstall")
    slots=root/"slots"
    if slots.is_symlink() or not slots.is_dir():
        raise OfflineProductLifecycleError("unsafe slots location")
    members=list(slots.iterdir())
    if not members:
        raise OfflineProductLifecycleError("installed slots absent")
    for p in members:
        if (p.is_symlink() or not p.is_dir() or
                SLOT_NAME.fullmatch(p.name) is None or
                {x.name for x in p.iterdir()} != {
                    RELEASE_NAME,"venv","ui","locked_requirements.txt","receipt.json"}):
            raise OfflineProductLifecycleError("unexpected customer data; uninstall denied")
        if ((p/RELEASE_NAME).is_symlink() or (p/"venv").is_symlink()
                or (p/"ui").is_symlink()):
            raise OfflineProductLifecycleError("linked installed path; uninstall denied")
    # Exact opt-in recipient only. Existing customer root is preserved but
    # no installed product or active pointer remains.
    for p in members:
        shutil.rmtree(p)
    slots.rmdir()
    (root/"active.json").unlink()
    script=root/LAUNCHER_NAME
    if script.exists():
        if _read(script,6000)!=LAUNCHER.encode("utf-8"):
            raise OfflineProductLifecycleError("unknown launcher preserved")
        script.unlink()
    return {
        "schema":SCHEMA,"status":"PRIVATE_TECHNICAL_RECIPIENT_UNINSTALLED_NO_GO",
        "removed_registered_slots":len(members),
        "recipient_directory_preserved":True,
        "customer_distribution_authorized":False,
    }



def serve_selected(
    recipient: Path, *, public_pem: bytes, expected_owner_key_id: str,
    expected_recipient_token_sha256: str, expected_rights_packet_sha256: str,
    min_serial: int, port: int = 0,
) -> int:
    """Private localhost surface: genuine selected signature checked EVERY GET."""
    from . import local_v1_app_v01 as app
    if type(port) is not int or (port!=0 and not 1024<=port<=65535):
        raise OfflineProductLifecycleError("unapproved loopback port")
    receipt=verify_selected(
        recipient,public_pem=public_pem,expected_owner_key_id=expected_owner_key_id,
        expected_recipient_token_sha256=expected_recipient_token_sha256,
        expected_rights_packet_sha256=expected_rights_packet_sha256,min_serial=min_serial)
    slot=receipt["active_slot"]
    child=recipient/"slots"/slot/"venv"/"Scripts"/"python.exe"
    if Path(sys.executable).resolve()!=child.resolve():
        raise OfflineProductLifecycleError("run ONLY authenticated active installed Python")
    ui=recipient/"slots"/slot/"ui"/"UCIE"
    if (not (ui/".git").is_dir() or ui.is_symlink()
            or (ui/"runtime").exists()):
        raise OfflineProductLifecycleError("unsafe recipient local UI root")
    parent=app.make_handler(ui)

    class PrivateVerifiedHandler(parent):
        def do_GET(self):
            try:
                verify_selected(
                    recipient,public_pem=public_pem,
                    expected_owner_key_id=expected_owner_key_id,
                    expected_recipient_token_sha256=expected_recipient_token_sha256,
                    expected_rights_packet_sha256=expected_rights_packet_sha256,
                    min_serial=min_serial,now=datetime.now(timezone.utc))
            except (OSError,TypeError,ValueError):
                return self.reply(403,"UCIE_PRIVATE_ENTITLEMENT_REVOKED_NO_GO",
                                  "text/plain; charset=utf-8")
            from urllib.parse import urlsplit
            if urlsplit(self.path).path=="/local/health":
                return self.reply(200,json.dumps({
                    "schema":SCHEMA,
                    "status":"SIGNED_TECHNICAL_OFFLINE_LOCAL_PREVIEW_NO_GO",
                    "private_entitlement_reverified_per_request":True,
                    "operating_database_writes":0,
                    "owner_real_customer_approval_proven":False,
                    "customer_distribution_authorized":False,
                },sort_keys=True),"application/json; charset=utf-8")
            return super().do_GET()

    with app.LOCAL_SERVER_CLASS(("127.0.0.1",port),PrivateVerifiedHandler) as server:
        print(json.dumps({
            "schema":SCHEMA,
            "status":"SIGNED_CUSTOMER_LOCAL_TECHNICAL_PREVIEW_NO_GO",
            "url":"http://127.0.0.1:"+str(server.server_port)+"/local",
            "signed_active_slot_verified":True,
            "customer_distribution_authorized":False,
            "owner_private_key_accessed":False,
            "host_service_registered":False,
        },sort_keys=True),flush=True)
        server.serve_forever(poll_interval=0.5)
    return 0


def main(argv: list[str] | None = None) -> int:
    import argparse
    parser=argparse.ArgumentParser(
        description="UCIE signed private offline technical recipient, not commercial release")
    parser.add_argument("--action",choices=("verify","stage","rollback","remove","serve"),required=True)
    parser.add_argument("--recipient-root",type=Path,required=True)
    parser.add_argument("--bundle",type=Path)
    parser.add_argument("--public-trust-pem",type=Path)
    parser.add_argument("--expected-owner-key-id")
    parser.add_argument("--recipient-token-sha256")
    parser.add_argument("--rights-packet-sha256")
    parser.add_argument("--min-serial",type=int,default=0)
    parser.add_argument("--python",type=Path)
    parser.add_argument("--consent",default="")
    parser.add_argument("--port",type=int,default=0)
    args=parser.parse_args(argv)
    try:
        root=args.recipient_root
        if args.action=="remove":
            result=remove_technical_install(root,consent=args.consent)
        else:
            if args.public_trust_pem is None:
                raise OfflineProductLifecycleError("separate approved PUBLIC trust key required")
            key=_read(args.public_trust_pem,2000)
            kwargs=dict(
                public_pem=key,expected_owner_key_id=args.expected_owner_key_id,
                expected_recipient_token_sha256=args.recipient_token_sha256,
                expected_rights_packet_sha256=args.rights_packet_sha256,
                min_serial=args.min_serial)
            if args.action=="verify":
                result=verify_selected(root,**kwargs)
            elif args.action=="rollback":
                result=rollback(root,consent=args.consent,**kwargs)
            elif args.action=="stage":
                if args.bundle is None or args.python is None:
                    raise OfflineProductLifecycleError("signed bundle and exact Python required")
                result=install_or_update(
                    root,args.bundle,python=args.python,consent=args.consent,**kwargs)
            else:
                return serve_selected(root,port=args.port,**kwargs)
        print(json.dumps(result,sort_keys=True),flush=True)
        return 0
    except (OSError,TypeError,KeyError,ValueError) as exc:
        print(json.dumps({
            "schema":SCHEMA,"status":"PRIVATE_OFFLINE_RECIPIENT_FAIL_CLOSED_NO_GO",
            "reason_type":type(exc).__name__,
            "customer_distribution_authorized":False,
        },sort_keys=True))
        return 2


